// .env  ->  firmware secrets.h   (git-ignored; compiled into the firmware you flash)
// The ESP32 cannot read your PC's .env at runtime, so the values are baked in at build time.
// Writes:
//   esp32/animation_client/secrets.h              (standalone test client)
//   ../firmware/AIDeskCompanion/secrets.h         (full AIDeskCompanion firmware, if that folder exists)
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, loadEnv } from './lib/env.mjs';

const env = loadEnv({ required: ['DEVICE_TOKEN', 'API_BASE', 'WIFI_SSID', 'WIFI_PASSWORD'] });
const cString = v => '"' + String(v).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/[\r\n]/g, '') + '"';

// Optional extras used only by the AIDeskCompanion firmware (Config.h picks them up if defined).
let optional = '';
if (env.WEATHER_API_KEY) optional += `#define SECRET_WEATHER_API_KEY ${cString(env.WEATHER_API_KEY)}\n`;
if (env.WEATHER_LOCATION) optional += `#define SECRET_WEATHER_LOCATION ${cString(env.WEATHER_LOCATION)}\n`;

const header = `// GENERATED by scripts/gen-firmware-secrets.mjs from .env - DO NOT EDIT, DO NOT COMMIT.
#pragma once
#define SECRET_WIFI_SSID ${cString(env.WIFI_SSID)}
#define SECRET_WIFI_PASSWORD ${cString(env.WIFI_PASSWORD)}
#define SECRET_API_BASE ${cString(env.API_BASE.replace(/\/$/, ''))}
#define SECRET_DEVICE_TOKEN ${cString(env.DEVICE_TOKEN)}
`;

const targets = [
  { file: path.join(ROOT, 'esp32', 'animation_client', 'secrets.h'), body: header, label: 'esp32/animation_client/secrets.h' },
  { file: path.join(ROOT, '..', 'firmware', 'AIDeskCompanion', 'secrets.h'), body: header + optional, label: '../firmware/AIDeskCompanion/secrets.h' }
];
for (const t of targets) {
  if (!fs.existsSync(path.dirname(t.file))) continue;
  fs.writeFileSync(t.file, t.body, { mode: 0o600 });
  console.log(`Wrote ${t.label} (git-ignored).`);
}
console.log('Now compile/upload the sketch from Arduino IDE or arduino-cli.');
